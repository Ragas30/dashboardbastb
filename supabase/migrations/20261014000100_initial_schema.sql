create type public.defect_status as enum ('OPEN', 'ON_PROGRESS', 'COMPLETED');
create type public.pic_status as enum ('ACTIVE', 'INACTIVE');

create table public.master_pics (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) > 0),
  status public.pic_status not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.defects (
  id bigint generated by default as identity primary key,
  project_cluster text not null check (length(trim(project_cluster)) > 0),
  unit text not null check (length(trim(unit)) > 0),
  defect_date date not null,
  total_defect integer not null check (total_defect >= 1),
  pic_id bigint not null references public.master_pics(id),
  target_repair date not null,
  status public.defect_status not null default 'OPEN',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index defects_pic_id_idx on public.defects(pic_id);
create index defects_status_idx on public.defects(status);
create index defects_defect_date_idx on public.defects(defect_date);

create or replace function public.set_updated_at() returns trigger
language plpgsql set search_path = public as $$
begin new.updated_at = now(); return new; end;
$$;

create trigger master_pics_set_updated_at before update on public.master_pics
for each row execute function public.set_updated_at();
create trigger defects_set_updated_at before update on public.defects
for each row execute function public.set_updated_at();

alter table public.master_pics enable row level security;
alter table public.defects enable row level security;

create policy "authenticated users can manage master pics" on public.master_pics
for all to authenticated using (true) with check (true);
create policy "authenticated users can manage defects" on public.defects
for all to authenticated using (true) with check (true);
