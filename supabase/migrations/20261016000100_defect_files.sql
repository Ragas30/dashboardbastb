create type public.defect_file_stage as enum ('BEFORE', 'AFTER');

create table public.defect_files (
  id bigint generated by default as identity primary key,
  defect_id bigint not null references public.defects(id) on delete cascade,
  stage public.defect_file_stage not null,
  file_path text not null,
  file_name text not null,
  file_size integer not null check (file_size > 0),
  created_at timestamptz not null default now()
);

create index defect_files_defect_id_idx on public.defect_files(defect_id);

alter table public.defect_files enable row level security;

create policy "authenticated users can manage defect files" on public.defect_files
for all to authenticated using (true) with check (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('defect-files', 'defect-files', false, 5242880, array['application/pdf'])
on conflict (id) do update
set public = false,
    file_size_limit = 5242880,
    allowed_mime_types = array['application/pdf'];

create policy "authenticated users can read defect files" on storage.objects
for select to authenticated using (bucket_id = 'defect-files');

create policy "authenticated users can upload defect files" on storage.objects
for insert to authenticated with check (bucket_id = 'defect-files');

create policy "authenticated users can delete defect files" on storage.objects
for delete to authenticated using (bucket_id = 'defect-files');
