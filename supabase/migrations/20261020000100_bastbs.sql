create table public.bastbs (
  id bigint generated by default as identity primary key,
  cluster text not null check (length(trim(cluster)) > 0),
  no_unit text not null check (length(trim(no_unit)) > 0),
  bastb_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index bastbs_cluster_idx on public.bastbs(cluster);
create index bastbs_no_unit_idx on public.bastbs(no_unit);
create trigger bastbs_set_updated_at before update on public.bastbs
for each row execute function public.set_updated_at();
alter table public.bastbs enable row level security;
create policy "authenticated users can manage bastbs" on public.bastbs
for all to authenticated using (true) with check (true);

alter table public.defects add column bastb_id bigint references public.bastbs(id) on delete set null;
create index defects_bastb_id_idx on public.defects(bastb_id);
